-- Every measure line below is copied verbatim from that file. Only the measures the value profile takes are kept
-- (slice 1, Q6 and profile 1b), and the CTE/FROM scaffolding is dropped: Resource Explorer assembles ONE
-- aggregate SELECT per table from these per-column measures (surveyors/database/quality/value_profile.py)
-- instead of one query per column. The TG-IF block names are upstream's flags, evaluated by general_type:
--   is_table              once per table (upstream: in every branch)
--   is_type_A             general_type = 'A'  (whole-table and, with no sampling, the sampleable measures)
--   is_not_A              general_type <> 'A'
--   is_distinct_countable general_type NOT IN ('A', 'X')  (upstream also counts the X types it can compare;
--                         slice 1 does not profile X distinct counts)
--   is_type_D             general_type = 'D'
--   is_type_N             general_type = 'N'  (profile 1b)
--   is_N_decimal          general_type = 'N' and the column is decimal (upstream's is_decimal, read from the
--                         target's catalog: general_type.is_decimal)  (profile 1b)
--   is_N_exact_sum        general_type = 'N' and logical_type 'integer' or decimal (general_type.exact_sum)  (profile 1b)
--   is_type_B             general_type = 'B'  (profile 1b)
--   is_A_text             general_type = 'A'  (step 7: the four whole-table text measures upstream takes in its
--                         `whole_table_measures` block, upstream lines 16-21; the sampled text-shape measures are in
--                         text_shape.sql)
-- Placeholders: {COL_NAME}, {DATA_SCHEMA}, {DATA_TABLE} (identifiers, double quotes doubled), {COL_NUM} (the quoted
-- column, cast ::NUMERIC for money, upstream's PostgresqlFlavorService.numeric_value) and
-- {RUN_DATE} ('YYYY-MM-DD HH:MM:SS', generated by Resource Explorer, never user input).
-- A `<%NAME;...%>` call is upstream's templated function (templated_functions.yaml beside this file), expanded
-- in the vendored text before any placeholder is filled.
-- TG-IF is_table
    COUNT(*) AS record_ct,
-- TG-ENDIF
-- TG-IF is_type_A
    COUNT("{COL_NAME}") AS value_ct,
    COUNT(DISTINCT "{COL_NAME}") AS distinct_value_ct,
    SUM(CASE WHEN "{COL_NAME}" IS NULL THEN 1 ELSE 0 END) AS null_value_ct,
    SUM(CASE
          WHEN "{COL_NAME}" = '' THEN 1
                               ELSE 0
        END) AS zero_length_ct,
    SUM( CASE
           WHEN LOWER("{COL_NAME}") SIMILAR TO '(.{1,}|-{1,}|\?{1,}|\s{1,}|0{2,}|9{2,}|x{2,}|z{2,})' THEN 1
           WHEN LOWER("{COL_NAME}") IN ('blank','error','missing','tbd',
                                      'n/a','#na','none','null','unknown')           THEN 1
           WHEN LOWER("{COL_NAME}") IN ('(blank)','(error)','(missing)','(tbd)',
                                      '(n/a)','(#na)','(none)','(null)','(unknown)') THEN 1
           WHEN LOWER("{COL_NAME}") IN ('[blank]','[error]','[missing]','[tbd]',
                                      '[n/a]','[#na]','[none]','[null]','[unknown]') THEN 1
                                                                                     ELSE 0
         END ) AS filled_value_ct,
    MIN(LENGTH(CAST("{COL_NAME}" AS TEXT))) AS min_length,
    MAX(LENGTH(CAST("{COL_NAME}" AS TEXT))) AS max_length,
    AVG(NULLIF(LENGTH(CAST("{COL_NAME}" AS TEXT)), 0)::FLOAT) AS avg_length,
-- TG-ENDIF
-- TG-IF is_not_A
  COUNT("{COL_NAME}") AS value_ct,
  SUM(CASE WHEN "{COL_NAME}" IS NULL THEN 1 ELSE 0 END) AS null_value_ct,
-- TG-ENDIF
-- TG-IF is_distinct_countable
  COUNT(DISTINCT "{COL_NAME}") AS distinct_value_ct,
-- TG-ENDIF
-- TG-IF is_type_D
  CASE
         WHEN MIN("{COL_NAME}") IS NULL THEN NULL
         ELSE GREATEST(MIN("{COL_NAME}"), '0001-01-01')
       END AS min_date,
  MAX("{COL_NAME}") AS max_date,
  SUM(CASE
        WHEN <%DATEDIFF_MONTH;"{COL_NAME}";'{RUN_DATE}'%> > 60 THEN 1
                                                            ELSE 0
      END) AS before_5yr_date_ct,
  SUM(CASE
          WHEN <%DATEDIFF_MONTH;"{COL_NAME}";'{RUN_DATE}'%> > 240 THEN 1
                                                              ELSE 0
        END) AS before_20yr_date_ct,
  SUM(CASE
        WHEN "{COL_NAME}" > '{RUN_DATE}' THEN 1 ELSE 0
      END) AS future_date_ct,
  COUNT(DISTINCT <%DATEDIFF_DAY;"{COL_NAME}";'{RUN_DATE}'%>) AS date_days_present,
-- TG-ENDIF
-- TG-IF is_type_N
  SUM( 1 - ABS(SIGN("{COL_NAME}"::NUMERIC)) )::BIGINT AS zero_value_ct,
  MIN({COL_NUM}) AS min_value,
  MAX({COL_NUM}) AS max_value,
  AVG(CAST("{COL_NAME}"::NUMERIC AS FLOAT)) AS avg_value,
  STDDEV(CAST("{COL_NAME}"::NUMERIC AS FLOAT)) AS stdev_value,
-- TG-ENDIF
-- TG-IF is_N_decimal
  SUM(ROUND(CAST(ABS(MOD({COL_NUM}, 1)) AS NUMERIC(38,8)), 5)) AS fractional_sum,
-- TG-ENDIF
-- TG-IF is_N_exact_sum
  CASE WHEN MAX(ABS(CAST({COL_NUM} AS DOUBLE PRECISION))) < 1e20 AND COUNT({COL_NUM}) < 1e10
       THEN SUM(CASE WHEN ABS(CAST({COL_NUM} AS DOUBLE PRECISION)) < 1e20 THEN CAST({COL_NUM} AS NUMERIC(38,8)) END)
  END AS sum_value,
-- TG-ENDIF
-- TG-IF is_type_B
  SUM(CAST("{COL_NAME}" AS INTEGER)) AS boolean_true_ct,
-- TG-ENDIF
-- TG-IF is_A_text
    SUM(CASE
          WHEN TRIM("{COL_NAME}") ~ '^0(\.0*)?$' THEN 1 ELSE 0
        END) AS zero_value_ct,
    COUNT(DISTINCT UPPER(TRANSLATE("{COL_NAME}", ' '',.-', ''))) AS distinct_std_value_ct,
    LEFT(MIN(NULLIF("{COL_NAME}", '')), 100) AS min_text,
    LEFT(MAX(NULLIF("{COL_NAME}", '')), 100) AS max_text
-- TG-ENDIF
