/** The words of an Egeria-coordinated definition run: a run in which every step ended and some were refused is
 *  PARTIAL (amber cue + "2 of 4 ran", each reason on demand), red only for a step that FAILED; a cancel is one neutral
 *  cue; the started-by words say who coordinated and who started, with the reader's local time; the definition's
 *  description paragraph is not printed in the run block; the definition's last-run names the coordinated run. */
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { makeDomEnvironment, ensureLoaderRegistered } from './dom-harness.mjs';

ensureLoaderRegistered();
makeDomEnvironment();
const ns = await import('/static/next/stages/native-surveys.js');
const { localTime } = await import('/static/next/format.js');
const text = (h) => h.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();

const LINE = 'Database Analysis Survey · step 1 postgres_column_profile ○ not run · step 2 postgres_nested_columns ○ not run'
  + ' · step 3 db_derived ✓ report 4a2771da · step 4 postgres_operations ✓ report b7bdb30b · coordinated by Egeria · started by peterprofile';
const SUBMITTED = '2026-10-16T14:42:00';
const REFUSAL = 'the stored credential has SELECT on 3 of 61 relations';
const partialRun = (extra = {}) => ({
  state: 'partial', line: LINE, summary: '2 of 4 ran', submitted_at: SUBMITTED, read_at: new Date().toISOString(), error: '',
  steps: [{ report_guid: '' }, { report_guid: '' }, { report_guid: '4a2771da-0000' }, { report_guid: 'b7bdb30b-0000' }],
  problems: [{ step: 1, label: 'postgres_column_profile', kind: 'refused', reason: REFUSAL },
    { step: 2, label: 'postgres_nested_columns', kind: 'refused', reason: REFUSAL }], ...extra });
const row = (run) => ({ qualified_name: 'GovActionProcess::DatabaseAnalysisSurvey', kind: 're_definition',
  display_name: 'Database Analysis Survey', runnable: true, run,
  description: 'Every catalog-intent: analysis Postgres database analysis: value sampling. Regenerated by scripts/generate_database_survey_definition.py.' });

test('a run whose steps all ended with some refused is PARTIAL: amber cue and "2 of 4 ran", not the red failure', () => {
  const h = ns.nativeSurveyStatusHtml(row(partialRun()));
  assert.match(text(h), /◐ 2 of 4 ran/);
  assert.match(h, /data-native-partial/);
  assert.doesNotMatch(h, /<span class="text-state-warn" data-native-process-line>/, 'the line itself is not red');
  assert.doesNotMatch(text(h), /✗/);
  const full = ns.nativeSurveyRowHtml(row(partialRun()));
  assert.match(full, /title="partial"/, 'the row icon is the partial cue');
  assert.doesNotMatch(full, /title="error"/);
});

test('each refused step reason is on demand: hidden, then shown by "why"', async () => {
  const h = ns.nativeSurveyStatusHtml(row(partialRun()));
  assert.match(h, /<span hidden\s+data-native-partial-why/);
  assert.equal((h.match(new RegExp(REFUSAL, 'g')) || []).length >= 2, true);
  assert.match(h, /title="step 1 postgres_column_profile: the stored credential/);
});

test('a step that FAILED is still the red failure with its cross', () => {
  const h = ns.nativeSurveyStatusHtml(row({ state: 'failed', line: 'Database Analysis Survey · step 1 postgres_column_profile ✗ survey-failed',
    submitted_at: SUBMITTED, steps: [], problems: [], read_at: new Date().toISOString(), error: '' }));
  assert.match(h, /text-state-warn" data-native-process-line/);
  assert.match(text(h), /✗ survey-failed/);
  assert.match(ns.nativeSurveyRowHtml(row({ state: 'failed', line: 'x', submitted_at: SUBMITTED, steps: [] })), /title="error"/);
});

test('the start time is the reader local time from the stored submission stamp, not a UTC date', () => {
  const h = ns.nativeSurveyStatusHtml(row(partialRun()));
  const want = localTime(SUBMITTED);
  assert.ok(want, 'localTime reads a naive stamp as UTC');
  assert.match(text(h), new RegExp(`started by peterprofile · ${want.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`));
  assert.doesNotMatch(text(h), /10-16/);
});

test('the definition description paragraph is not printed under the run line', () => {
  const h = ns.nativeSurveyRowHtml(row(partialRun()));
  assert.doesNotMatch(text(h), /Every catalog-intent/);
  assert.doesNotMatch(text(h), /Regenerated by/);
  assert.match(text(ns.nativeSurveyRowHtml({ ...row({ state: 'not_run' }), kind: 'survey_existing', description: 'Egeria says hello' })), /Egeria says hello/);
});

test('a cancel is one neutral cue: not the tick, not the cross', () => {
  const r = row({ state: 'failed', egeria_status: 'CANCELLED', message: 'cancelled in Egeria', read_at: new Date().toISOString(), engine_action_guid: 'g' });
  const h = ns.nativeSurveyRowHtml({ ...r, kind: 'survey_existing' });
  assert.match(h, /title="cancelled"[^>]*>⊘</);
  assert.match(text(h), /cancelled in Egeria/);
  assert.doesNotMatch(text(h), /[✓✗✕]/);
});

test('the definition last-run names the coordinator and who started it', async () => {
  const { lastRunHtml } = await import('/static/next/app.js');
  const when = new Date(Date.now() - 21 * 60000).toISOString();
  const h = text(lastRunHtml({ last_run_at: when, last_run_status: 'partial', last_run_coordinated_by: 'egeria', last_run_by: 'peterprofile',
    last_run_errors: ['step 1 postgres_column_profile refused: x'] }));
  assert.match(h, /ran 21m ago · coordinated by Egeria · started by peterprofile/);
  assert.match(text(lastRunHtml({ last_run_at: when, last_run_status: 'ok', last_run_coordinated_by: 'egeria' })), /coordinated by Egeria$/);
});
