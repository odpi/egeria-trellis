def _guards_declared() -> list[str]:
    """The producedGuards in the GENERATED declaration document (E1), read back out of it."""
    import importlib.util
    from pathlib import Path

    path = Path(__file__).resolve().parent.parent / "scripts" / "generate_engine_host_declaration.py"
    spec = importlib.util.spec_from_file_location("gen_engine_host_decl", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    text = mod.render()
    block = re.search(r"### Produced Guards\n(.+)\n", text).group(1)
    return [g.strip() for g in block.split(",")]


