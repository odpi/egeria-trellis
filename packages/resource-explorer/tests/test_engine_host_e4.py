def test_a_failed_publish_completes_survey_failed_with_the_error_and_no_report_guid(reg, egeria, no_connection):
    egeria.add_action("ea-pubfail")
    _sweep(reg)
    egeria.fail["create_asset"] = RuntimeError("OMAG-COMMON-500-001 the repository is unavailable")
    _run_queue_once(reg)

    done = egeria.actions["ea-pubfail"]["completion"]
    assert done["guards"] == ["survey-failed"], done
    assert done["status"] == "FAILED"
    assert "the repository is unavailable" in done["message"]
    assert "was not published" in done["message"], "with no report GUID the words say no report exists"
    assert "surveyReport" not in json.dumps(done["targets"])
    sent = egeria.of("AutomatedCuration").record_completion_status.call_args_list
    assert sent and all(c.kwargs.get("output_guards") == ["survey-failed"] for c in sent), sent
    row = _row(reg)
    assert row["state"] == "failed"
    assert row["target"]["outcome"]["report_guid"] == ""
    assert row["target"]["outcome"]["guard"] == "survey-failed"


def test_completion_is_recorded_only_after_the_outcome_is_stored_on_the_row(reg, egeria, no_connection):
    """The row must already carry the report GUID and annotation count when Egeria is told."""
    egeria.add_action("ea-order")
    _sweep(reg)
    seen = {}
    complete = egeria.of("AutomatedCuration").record_completion_status.side_effect

    def check_row_first(engine_action_guid, *args, **kwargs):
        seen.update(_row(reg)["target"].get("outcome") or {})
