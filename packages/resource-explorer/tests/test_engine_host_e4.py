def _refusal(message_id: str, text: str):
    from pyegeria.core._exceptions import PyegeriaUnauthorizedException

    return PyegeriaUnauthorizedException(None, context={"caller method": "fake"}, additional_info={
        "relatedHTTPCode": 403, "exceptionErrorMessageId": message_id,
        "exceptionErrorMessage": f"{message_id} {text}"})


class FakeEgeria:
    """Engine actions, elements and relationships, with Egeria's own gates (C5, C7, C8)."""

    TERMINAL = {"ACTIONED": "COMPLETED", "INVALID": "INVALID", "FAILED": "FAILED", "OTHER": "OTHER"}

    def __init__(self, monkeypatch):
        from resource_explorer import egeria_clients

        self.actions: dict[str, dict] = {}
        self.elements: dict[str, dict] = {}          # guid -> {"type", "body"}
        self.relationships: list[dict] = []          # {"type", "end1", "end2"}
        self.classifications: list[tuple] = []       # (kind, guid, body)
        self.calls: list[tuple] = []                 # (client class, method, principal)
        self.built: list[tuple[str, str]] = []       # (client class, Egeria user the client was built for)
        self.specs: dict[type, object] = {}
        self.fail: dict[str, BaseException] = {}     # method name -> exception to raise (once per entry)
        self.fail_build: dict[str, BaseException] = {}   # client class name -> exception its constructor raises
        self.fail_nth: dict[str, tuple[int, BaseException]] = {}   # method -> (raise on this call number, exc)
        # Engine host step 4: native SurveyReports (M2 shape, by GUID), element graphs answered by
        # get_all_related_elements (by GUID; an action not listed answers as a lone action), processes declared in
        # Egeria (by qualifiedName), assets get_metadata_element_by_guid finds, and the process starts made.
        self.native_reports: dict[str, dict] = {}
        self.graphs: dict[str, object] = {}
        #: Fields an annotation was sent with that Egeria 6.2's bean for its class does not have, and so drops.
        self.dropped: list[dict] = []
        self.declared: set[str] = set()
        self.assets: set[str] = set()
        self.process_starts: list[dict] = []
        monkeypatch.setattr(egeria_clients, "_build", self._build)

    # -- the constructor seam --------------------------------------------------

    def _build(self, cls, view_server, platform_url, user_id, password):
        self.built.append((cls.__name__, user_id))
        if cls.__name__ in self.fail_build:
            raise self.fail_build.pop(cls.__name__)
        spec = self.specs.get(cls)
        if spec is None:
            spec = create_autospec(cls, spec_set=True, instance=True)
            self._wire(cls, spec)
            self.specs[cls] = spec
        return spec

    def of(self, name: str):
        return next(s for c, s in self.specs.items() if c.__name__ == name)

    def _record(self, cls_name: str, method: str):
        from resource_explorer.egeria_clients import current_principal

        try:
            who = current_principal()
        except Exception:  # noqa: BLE001 - recorded as "nobody", which a test then fails on
            who = None
        self.calls.append((cls_name, method, who))
        nth = self.fail_nth.get(method)
        if nth and sum(1 for c in self.calls if c[1] == method) == nth[0]:
            raise nth[1]
        exc = self.fail.pop(method, None)
        if exc is not None:
            raise exc

    def _wire(self, cls, spec):
        name = cls.__name__
        rec = self._record

        def wrap(method, fn):
            def inner(*args, **kwargs):
                rec(name, method)
                return fn(*args, **kwargs)
            getattr(spec, method).side_effect = inner

        if name == "AutomatedCuration":
            wrap("get_active_engine_actions", self._active)
            wrap("get_active_claimed_engine_actions", self._active_claimed)
            wrap("claim_engine_action", self._claim)
            wrap("update_engine_action_status", self._status)
            wrap("record_completion_status", self._complete)
            wrap("initiate_gov_action_process", self._start_process)
            # By-name lookups: annotations are new (a miss); anything else is the catalogued database element.
            wrap("get_guid_for_name", lambda name, *a, **k:
                 "No elements found" if str(name).startswith("Annotation::") else DB_GUID)
        elif name == "MetadataExpert":
            wrap("get_metadata_guid_by_unique_name", lambda *a, **k: ENGINE_GUID)
            wrap("create_related_elements", self._relate)
            wrap("get_related_metadata_elements", self._related)
            wrap("get_metadata_element_by_guid", self._element)
            wrap("get_all_related_elements", self._graph)
            wrap("get_metadata_element_by_unique_name", self._by_unique_name)
        elif name == "AssetMaker":
            wrap("create_asset", self._create_asset)
            wrap("get_asset_by_guid", self._asset)
        elif name == "DataDiscovery":
            wrap("create_annotation", self._create_annotation)
        elif name == "ClassificationExplorer":
            wrap("add_ownership_to_element", lambda guid, body=None, *a, **k:
                 self.classifications.append(("Ownership", guid, body)))
            wrap("add_zone_membership", lambda guid, body=None, *a, **k:
                 self.classifications.append(("ZoneMembership", guid, body)))
        elif name == "ActorManager":
            wrap("get_user_identities_by_name", lambda *a, **k: "No elements found")

    # -- engine actions ----------------------------------------------------------

    def add_action(self, guid: str, *, target: str | list | None = DB_GUID, status: str = "APPROVED",
                   claimed_by: str | None = None, requester: str = REQUESTER,
                   request_type: str = "re-db-derived", report: str | None = None,
                   target_name: str = "newAsset") -> dict:
        targets = [] if target is None else ([target] if isinstance(target, str) else list(target))
        action = {
            "class": "EngineActionElement",
            "elementHeader": {"guid": guid},
            "governanceEngineGUID": ENGINE_GUID,
            "governanceEngineName": "ResourceExplorerSurvey",
            "actionStatus": status,
            "requestType": request_type,
            "processingEngineUserId": claimed_by,
            "requesterUserId": requester,
            "requestedStartTime": 1_760_400_000_000,
            "actionTargetElements": [{"actionTargetName": target_name, "actionTargetGUID": t} for t in targets]
            + ([{"actionTargetName": "surveyReport", "actionTargetGUID": report}] if report else []),
            # what RE wrote:
            "statusUpdates": [], "completion": None,
        }
        self.actions[guid] = action
        return action

    def _active(self, start_from=0, page_size=0, output_format="JSON", report_spec="EngineAction", **kwargs):
        live = [a for a in self.actions.values() if a["actionStatus"] not in self.TERMINAL.values()]
        chunk = live[start_from:start_from + page_size] if page_size else live[start_from:]
        return chunk or "No elements found"

    def _active_claimed(self, governance_engine_guid, start_from=0, page_size=0):
        mine = [a for a in self.actions.values()
                if a["governanceEngineGUID"] == governance_engine_guid
                and a["processingEngineUserId"] == _daemon_user()
                and a["actionStatus"] in ("WAITING", "ACTIVATING", "IN_PROGRESS")]
        chunk = mine[start_from:start_from + page_size] if page_size else mine[start_from:]
        return chunk or "No elements found"

    def _claim(self, engine_action_guid):
        from resource_explorer.egeria_clients import current_principal

        a = self.actions[engine_action_guid]
        if a["actionStatus"] != "APPROVED" or a["processingEngineUserId"]:
            raise _refusal("OMAG-GENERIC-HANDLERS-403-003", "already claimed")
        a["actionStatus"] = "ACTIVATING"
        a["processingEngineUserId"] = current_principal().client_user

    def _claimant_check(self, a):
        from resource_explorer.egeria_clients import current_principal

        if a["processingEngineUserId"] != current_principal().client_user:
            raise _refusal("OMAG-GENERIC-HANDLERS-403-004", "not the claimant")

    def _status(self, engine_action_guid, status, body=None):
        a = self.actions[engine_action_guid]
        self._claimant_check(a)
        a["statusUpdates"].append(status)
        a["actionStatus"] = status

    def _complete(self, engine_action_guid, status, request_parameters=None, output_guards=None,
                  new_action_targets=None, completion_message=None, body=None):
        a = self.actions[engine_action_guid]
        if a["actionStatus"] in self.TERMINAL.values():
            # Egeria ignores a completion on an action that is no longer active, silently: no else branch in
            # EngineActionHandler.recordCompletionStatus (egeria main, generic-handlers, ~line 2734).
            return
        self._claimant_check(a)
        a["completion"] = {"status": status, "guards": list(output_guards or []),
                           "targets": list(new_action_targets or []), "message": completion_message or ""}
        a["actionStatus"] = self.TERMINAL[status]

    # -- elements --------------------------------------------------------------

    def _create_asset(self, asset_type=None, body=None):
        guid = _uuid()
        self.elements[guid] = {"type": (body or {}).get("properties", {}).get("typeName"), "body": body}
        parent = (body or {}).get("parentGUID")
        if parent:
            self.relationships.append({"type": body.get("parentRelationshipTypeName"), "end1": parent, "end2": guid})
        return guid

    def _create_annotation(self, body=None):
        props = (body or {}).get("properties") or {}
        kept, unknown = egeria_keeps(props)
        if unknown:
            # Egeria's bean ignores unknown fields (@JsonIgnoreProperties(ignoreUnknown=true)): the live platform
            # stores the annotation WITHOUT them and says nothing. The fake does the same, so a test reading the
            # stored body sees what Egeria keeps, and records each drop in `dropped` for a test to assert on.
            self.dropped.append({"class": props["class"], "analysisStep": props.get("analysisStep"),
                                 "fields": unknown})
            body = {**body, "properties": kept}
        guid = _uuid()
        self.elements[guid] = {"type": "Annotation", "body": body}
        parent = (body or {}).get("parentGUID")
        if parent:
            self.relationships.append({"type": body.get("parentRelationshipTypeName") or "ReportedAnnotation",
                                       "end1": parent, "end2": guid})
        return guid

    def _relate(self, body=None):
        guid = _uuid()
        self.relationships.append({"type": body["typeName"], "end1": body["metadataElement1GUID"],
                                   "end2": body["metadataElement2GUID"], "guid": guid})
        return guid

    def _related(self, element_guid, relationship_type=None, body=None, start_from=0, page_size=0,
                 starting_at_end=0, *args, **kwargs):
        hits = [r for r in self.relationships if r["type"] == relationship_type and r["end1"] == element_guid]
        if not hits:
            return "No elements found"
        return {"elementList": [{"element": {"elementGUID": r["end2"]}} for r in hits]}

    def _element(self, guid, *args, **kwargs):
        a = self.actions.get(guid)
        if a is None and guid in self.assets:
            return {"elementGUID": guid, "elementProperties": {"propertyValueMap": {}}}
        if a is None:
            return "No elements found"
        props = {"activityStatus": {"symbolicName": a["actionStatus"]},
                 "completionMessage": {"primitiveValue": (a["completion"] or {}).get("message", "")}}
        return {"elementGUID": guid, "elementProperties": {"propertyValueMap": props}}

    def _graph(self, guid=None, starting_at_end=0, start_from=0, page_size=500, graph_query_depth=5,
               relationships_page_size=0, body=None, **kwargs):
        if guid in self.graphs:
            return self.graphs[guid]
        a = self.actions.get(guid)
        if a is None:
            return "No elements found"
        props = {"activityStatus": {"class": "EnumTypePropertyValue", "symbolicName": a["actionStatus"]},
                 "requestType": {"primitiveValue": a["requestType"]},
                 "requesterUserId": {"primitiveValue": a["requesterUserId"]}}
        # A lone action: its targets only, no ControlFlow and no process-instance anchor.
        return {"startingElement": {"elementGUID": guid, "classifications": [],
                                    "elementProperties": {"propertyValueMap": props}},
                "elementList": [{"type": {"typeName": "ActionTarget"}, "elementAtEnd1": False,
                                 "relationshipProperties": {"propertiesAsStrings": {
                                     "actionTargetName": t["actionTargetName"]}},
                                 "element": {"elementGUID": t["actionTargetGUID"]}}
                                for t in a["actionTargetElements"]]}

    def _by_unique_name(self, name=None, property_name="qualifiedName", *args, **kwargs):
        if name in self.declared:
            return {"elementGUID": "decl-" + str(name)[-8:], "elementProperties": {}}
        return "No elements found"

    def _start_process(self, action_type_qualified_name, request_source_guids=None, action_targets=None,
                       start_time=None, request_parameters=None, orig_service_name=None, orig_engine_name=None):
        self.process_starts.append({"process": action_type_qualified_name, "action_targets": action_targets,
                                    "request_parameters": request_parameters})
        return f"pi-{len(self.process_starts)}"

    def _asset(self, guid, *args, **kwargs):
        if guid in self.native_reports:
            return self.native_reports[guid]
        el = self.elements.get(guid)
        if el is None:
            return "No elements found"
        anns = [self.elements[r["end2"]] | {"guid": r["end2"]} for r in self.relationships
                if r["end1"] == guid and self.elements.get(r["end2"], {}).get("type") == "Annotation"]
        originator = next((r["end1"] for r in self.relationships
                           if r["type"] == "ReportOriginator" and r["end2"] == guid), "")
        return {
            "elementHeader": {"guid": guid},
            "properties": el["body"]["properties"],
            "reportOriginator": {"relatedElement": {"elementHeader": {"guid": originator}}} if originator else {},
            "reportedAnnotations": [{"relatedElement": {
                "elementHeader": {"guid": a["guid"], "type": {"typeName": "Annotation"}},
                "properties": (a["body"] or {}).get("properties", {})}} for a in anns],
        }

    # -- what the tests read ---------------------------------------------------

    def reports(self) -> list[tuple[str, dict]]:
        return [(g, e["body"]) for g, e in self.elements.items() if e["type"] == "SurveyReport"]

    def annotations_under(self, report_guid: str) -> int:
        return sum(1 for r in self.relationships if r["end1"] == report_guid
                   and self.elements.get(r["end2"], {}).get("type") == "Annotation")

    def method_calls(self, method: str) -> list[tuple]:
        return [c for c in self.calls if c[1] == method]


