def test_a_claimed_action_runs_publishes_a_native_shaped_report_and_completes(reg, egeria, no_connection):
    egeria.add_action("ea-1")
    assert _sweep(reg).claimed == ["ea-1"]
    assert _run_queue_once(reg) is not None

    action = egeria.actions["ea-1"]
    assert action["statusUpdates"] == ["IN_PROGRESS"]
    done = action["completion"]
    assert done["status"] == "ACTIONED" and done["guards"] == ["survey-completed"], done
    assert action["actionStatus"] == "COMPLETED"

    [(report_guid, body)] = egeria.reports()
    props = body["properties"]
    assert re.fullmatch(rf"SurveyReport::re-db-derived::{DB_GUID}::\S+", props["qualifiedName"]), props
    assert props["purpose"] == "re-db-derived"
    assert props["authors"] == [_daemon_user()]
    assert body["parentGUID"] == DB_GUID and body["parentRelationshipTypeName"] == "ReportSubject"
    assert {"type": "ReportOriginator", "end1": "ea-1", "end2": report_guid} in [
        {k: r[k] for k in ("type", "end1", "end2")} for r in egeria.relationships]
    assert done["targets"] == [{"actionTargetName": "surveyReport", "actionTargetGUID": report_guid}]

    row = _row(reg)
    assert row["state"] == "succeeded"
    outcome = row["target"]["outcome"]
    assert outcome["report_guid"] == report_guid
    assert outcome["guard"] == "survey-completed"
    assert outcome["annotation_count"] == egeria.annotations_under(report_guid) > 0
    assert row["target"]["completion_recorded_at"]


