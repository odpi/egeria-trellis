"""Test 9 of the engine-host design (§5.2): the generated Dr.Egeria declaration equals the registry.

The document under docs/dr-egeria/engine-host/ is generated by scripts/generate_engine_host_declaration.py from
DATABASE_STEP_REGISTRY. Its request type, guards and step key must match the registry entry and the names the
sweep dispatches on (engine_host.py), so changing either side fails here. It is never run automatically: the
owner runs it, so it must not be a bootstrap batch.
"""
from __future__ import annotations

import importlib.util
import re
import subprocess
import sys
from pathlib import Path

import pytest

PKG = Path(__file__).resolve().parent.parent
SCRIPT = PKG / "scripts" / "generate_engine_host_declaration.py"
DOC = PKG / "docs" / "dr-egeria" / "engine-host" / "resource-explorer-survey-engine.md"


def _script():
    spec = importlib.util.spec_from_file_location("generate_engine_host_declaration", SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _section(doc: str, command: str, heading: str, nth: int = 0) -> str:
    """The value under `### heading` in the nth `## command` block."""
    blocks = [b for b in doc.split("\n## ") if b.startswith(command + "\n")]
    block = blocks[nth]
    m = re.search(r"^### " + re.escape(heading) + r"\n(.*?)(?=\n### |\n___|\Z)", block, re.S | re.M)
    assert m, f"no '### {heading}' under '## {command}'"
    return m.group(1).strip()


def test_the_committed_document_is_what_the_generator_writes():
    assert DOC.read_text() == _script().render(), \
        "the engine-host declaration is stale: run scripts/generate_engine_host_declaration.py"


