def test_request_type_guards_and_step_key_match_the_registry_entry():
    from resource_explorer import engine_host
    from resource_explorer.surveyors.database.survey_definition_adapter import DATABASE_STEP_REGISTRY

    info = DATABASE_STEP_REGISTRY["db_derived"]
    doc = DOC.read_text()

    gat_qn = _section(doc, "Create Governance Action Type", "Qualified Name")
    assert gat_qn == "ResourceExplorerSurvey::re-db-derived"
    assert _section(doc, "Create Governance Action Type", "Description") == info.description
    guards = [g.strip() for g in _section(doc, "Create Governance Action Type", "Produced Guards").split(",")]
    assert guards == ["survey-completed", "survey-invalid", "survey-failed"]
    assert tuple(guards) == engine_host.SURVEY_GUARDS
    props = _section(doc, "Create Governance Action Type", "Additional Properties")
    assert f"| re_analysis_step | {info.step_key} |" in props
    assert "| executes_at | resource-explorer |" in props

    assert _section(doc, "Link Action to Action Executor", "Governance Action Type") == gat_qn
    assert _section(doc, "Link Action to Action Executor", "Governance Engine") == "ResourceExplorerSurvey"
    assert _section(doc, "Link Action to Action Executor", "Request Type") == "re-db-derived"

    # The sweep dispatches on exactly what the documents declare: this one re-db-derived, engine-host/steps/ every
    # other registry step (case 3, held to the registries by test_engine_host_case3).
    assert engine_host.supported_request_types()["re-db-derived"] == "db_derived"
    assert set(engine_host.supported_request_types()) == {engine_host.request_type_for_step(k)
                                                          for k in engine_host.registry_steps()}
    assert engine_host.ENGINE_QUALIFIED_NAME == "ResourceExplorerSurvey"


